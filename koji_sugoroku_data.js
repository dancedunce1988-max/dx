/* =========================================================================
   語の一覧の組み立て（すごろく用の語＋知識ドリルの故事成語ジャンルの語）。
   2026-11-20〜、本体の管理者画面（言葉スタンプを1つずつ選ぶ欄）でも同じ一覧を使うため、koji_sugoroku.html から移した。
   qd＝window.QUESTION_DATA（kokugo_data.js）。すごろくの画面・管理者画面の両方から kojiBuildWords(window.QUESTION_DATA) で呼ぶ。
   ========================================================================= */
function kojiDataItemFacet(it){
  const ins = it.instr || '';
  if(!ins && it.s) return { facet:'story', word:it.c[it.a], kind:'story2word' };
  if(ins.startsWith('次の故事成語の意味')) return { facet:'meaning', word:it.q, kind:'meaning' };
  if(ins.startsWith('この故事成語のもとになった')) return { facet:'story', word:it.q, kind:'word2story' };
  if(ins.startsWith('（')) return { facet:'usage', word:it.c[it.a], kind:'blank' };
  return null;
}
function kojiBuildWords(qd){
  const DATA_ITEMS = (qd && qd.cats && qd.cats.koji)
    ? qd.cats.koji.items.filter(it => it.from !== 'koji_sugoroku') : [];
  const WORDS = KOJI_WORDS.map(w => Object.assign({ rich:true, dataQs:{} }, w));
  DATA_ITEMS.forEach(it => {
    const f = kojiDataItemFacet(it);
    if(!f) return;
    let w = WORDS.find(x => x.word === f.word || x.dataWord === f.word);
    if(!w){ w = { id:'d_' + f.word, word:f.word, tier:it.lv || 2, rich:false, dataQs:{} }; WORDS.push(w); }
    if(!w.rich) w.tier = Math.min(w.tier, it.lv || 3);
    (w.dataQs[f.facet] = w.dataQs[f.facet] || []).push(Object.assign({ kind:f.kind }, it));
    if(!w.rich){
      const m = /「[^」]+」の読み方は「([^」]+)」/.exec(it.e || '');
      if(m && !w.yomi) w.yomi = m[1];
      if(f.kind === 'meaning') w.meaning = it.c[it.a];
      if(f.kind === 'story2word' && !w.story) w.story = it.q;
      if(f.kind === 'word2story' && !w.story) w.story = it.c[it.a];
    }
  });
  return { DATA_ITEMS, WORDS };
}
